"""Generates an SVG plot of the DQN metrics without external dependencies."""
import argparse
import csv
from collections import Counter
from pathlib import Path


def make_plot(metrics_path, output_path=None, window=50):
    metrics_path = Path(metrics_path)
    output_path = Path(output_path) if output_path else metrics_path.with_name("reward_moving_average.svg")
    with metrics_path.open(newline="", encoding="utf-8") as file:
        rows = list(csv.DictReader(file))
    if not rows:
        raise ValueError(f"There are no episodes in {metrics_path}")

    episodes = [int(row["episode"]) for row in rows]
    rewards = [float(row["total_reward"]) for row in rows]
    outcomes = Counter(row["outcome"] for row in rows)
    means = [sum(rewards[max(0, i - window + 1):i + 1]) /
             len(rewards[max(0, i - window + 1):i + 1]) for i in range(len(rewards))]
    width, height = 1000, 600
    left, right, top, bottom = 82, 28, 76, 70
    plot_w, plot_h = width - left - right, height - top - bottom
    low, high = min(rewards + means), max(rewards + means)
    margin = max((high - low) * 0.08, 1.0)
    low, high = low - margin, high + margin

    def point(index, value):
        x = left + (index / max(len(episodes) - 1, 1)) * plot_w
        y = top + (high - value) / (high - low) * plot_h
        return x, y

    def polyline(values):
        return " ".join(f"{point(i, value)[0]:.1f},{point(i, value)[1]:.1f}" for i, value in enumerate(values))

    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
             '<rect width="100%" height="100%" fill="#fff"/>',
             '<text x="500" y="29" text-anchor="middle" font-family="sans-serif" font-size="20" font-weight="bold">Reward per episode</text>',
             f'<text x="500" y="54" text-anchor="middle" font-family="sans-serif" font-size="14"><tspan fill="#238636">Landings: {outcomes["LANDED"]}</tspan><tspan dx="24" fill="#c62828">Crashes: {outcomes["CRASHED"]}</tspan><tspan dx="24" fill="#666">Timeouts: {outcomes["TIMEOUT"]}</tspan><tspan dx="24" fill="#333">Total: {len(rows)}</tspan></text>']
    for tick in range(5):
        value = low + (high - low) * tick / 4
        y = top + plot_h * (1 - tick / 4)
        parts += [f'<line x1="{left}" y1="{y:.1f}" x2="{width-right}" y2="{y:.1f}" stroke="#ddd"/>',
                  f'<text x="{left-10}" y="{y+4:.1f}" text-anchor="end" font-family="sans-serif" font-size="12">{value:.1f}</text>']
    parts += [f'<polyline points="{polyline(rewards)}" fill="none" stroke="#9bb7d4" stroke-width="1"/>',
              f'<polyline points="{polyline(means)}" fill="none" stroke="#d34b36" stroke-width="2.5"/>',
              f'<text x="{left + plot_w/2:.1f}" y="{height-22}" text-anchor="middle" font-family="sans-serif" font-size="14">Episode</text>',
              f'<text x="{left+8}" y="{top+18}" font-family="sans-serif" font-size="13" fill="#607d9b">Reward</text>',
               f'<text x="{left+115}" y="{top+18}" font-family="sans-serif" font-size="13" fill="#d34b36">Moving average ({window})</text>', '</svg>']
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(parts), encoding="utf-8")
    return output_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("metrics", nargs="?", default="runs/dqn/metrics.csv", help="CSV generated by train.py")
    parser.add_argument("--output", help="Output SVG path")
    parser.add_argument("--window", type=int, default=50, help="Episodes in the moving average")
    args = parser.parse_args()
    if args.window < 1:
        parser.error("--window must be positive")
    print(f"Plot saved to: {make_plot(args.metrics, args.output, args.window)}")


if __name__ == "__main__":
    main()
